# -*- coding: utf-8 -*-
"""
gui_sea_level.py — Sea Level Change GUI window.

Step-by-step workflow:
    1. Select input .bct file
    2. Enter sea level change (metres)
    3. Choose mode (constant / linear)
    4. Run

Can be run standalone: python gui_sea_level.py
"""

import customtkinter as ctk
from pathlib import Path
from typing import Optional

from gui_theme import (
    apply_theme, COLORS,
    make_button, make_label, make_entry,
    make_separator, make_step_header, make_file_row, make_status_label,
    make_radiobutton,
)
from gui_utils import (
    create_sub_window_layout, BackgroundTask,
    browse_file, clear_log,
    save_json_settings, load_json_settings,
    save_settings_dialog, load_settings_dialog,
    show_success_in_log, show_error_dialog,
    set_widgets_state,
)


MODULE_ID = "sea_level"
SETTINGS_VERSION = 1


class SeaLevelWindow(ctk.CTkToplevel):
    """Sea Level Change sub-module window."""

    def __init__(self, parent=None):
        super().__init__(parent)
        left, self.log_textbox, self.progress_bar, self.status_label, self.eta_label = \
            create_sub_window_layout(
                self, title="Sea Level Change",
                min_width=900, min_height=500,
            )

        self._interactive_widgets = []
        self._task: Optional[BackgroundTask] = None
        self._build_workflow(left)

    def _build_workflow(self, parent):
        pad = dict(anchor="w", padx=10)

        # ─── Step 1: Input File ──────────────────────────────────────────
        make_step_header(parent, 1, "Input File").pack(**pad, pady=(15, 5))
        make_label(
            parent,
            "Select an existing .bct file generated by RepD3D or Delft3D",
            font_key="body_sm", color=COLORS["text_dim"],
        ).pack(**pad)
        row_bct, self.bct_entry, self.bct_btn = make_file_row(parent, ".bct file")
        self.bct_btn.configure(command=lambda: browse_file(
            self.bct_entry, "Select .bct file",
            [("BCT files", "*.bct"), ("All files", "*.*")],
        ))
        row_bct.pack(fill="x", padx=10, pady=3)
        self._interactive_widgets.append(self.bct_btn)

        make_separator(parent).pack(fill="x", padx=10, pady=(12, 8))

        # ─── Step 2: Sea Level Change ────────────────────────────────────
        make_step_header(parent, 2, "Sea Level Change").pack(**pad, pady=(0, 5))
        sl_frame = ctk.CTkFrame(parent, fg_color="transparent")
        sl_frame.pack(fill="x", padx=10, pady=3)
        self.sl_entry = make_entry(sl_frame, placeholder="e.g., 0.5", width=120)
        self.sl_entry.pack(side="left", padx=(0, 8))
        make_label(sl_frame, "metres", font_key="body_sm").pack(side="left")
        self._interactive_widgets.append(self.sl_entry)

        make_separator(parent).pack(fill="x", padx=10, pady=(12, 8))

        # ─── Step 3: Mode ────────────────────────────────────────────────
        make_step_header(parent, 3, "Mode").pack(**pad, pady=(0, 5))
        self.mode_var = ctk.StringVar(value="linear")
        make_radiobutton(
            parent, "Linear interpolation (0 at start → target at end)",
            self.mode_var, "linear",
        ).pack(**pad, pady=2)
        make_radiobutton(
            parent, "Constant offset (same value at every timestep)",
            self.mode_var, "constant",
        ).pack(**pad, pady=2)

        make_separator(parent).pack(fill="x", padx=10, pady=(12, 8))

        # ─── Step 4: Run ─────────────────────────────────────────────────
        make_step_header(parent, 4, "Run").pack(**pad, pady=(0, 5))
        self.run_btn = make_button(
            parent, "Apply Sea Level Change",
            command=self._on_run, style="primary", width=250,
        )
        self.run_btn.pack(**pad, pady=(5, 5))

        # ─── Settings / Reset row ────────────────────────────────────────
        btn_row = ctk.CTkFrame(parent, fg_color="transparent")
        btn_row.pack(fill="x", padx=10, pady=(5, 20))
        self.save_btn = make_button(
            btn_row, "Save Settings", self._on_save_settings,
            style="settings", width=140,
        )
        self.save_btn.pack(side="left", padx=(0, 5))
        self.load_btn = make_button(
            btn_row, "Load Settings", self._on_load_settings,
            style="settings", width=140,
        )
        self.load_btn.pack(side="left", padx=(0, 5))
        self.reset_btn = make_button(
            btn_row, "Reset / Stop", self._on_reset,
            style="reset", width=140,
        )
        self.reset_btn.pack(side="left")
        self._interactive_widgets.extend([self.save_btn, self.load_btn])

    def _on_run(self):
        bct_file = self.bct_entry.get().strip()
        if not bct_file:
            show_error_dialog(self, "Missing input", "Please select a .bct file.")
            return

        sl_text = self.sl_entry.get().strip()
        if not sl_text:
            show_error_dialog(self, "Missing input", "Please enter a sea level change value.")
            return

        try:
            sl_value = float(sl_text)
        except ValueError:
            show_error_dialog(self, "Invalid input", f"'{sl_text}' is not a valid number.")
            return

        constant = self.mode_var.get() == "constant"

        set_widgets_state(self._interactive_widgets + [self.run_btn], "disabled")
        self.status_label.configure(text="Applying sea level change...")

        import backend_sea_level as bsl

        self._task = BackgroundTask(
            target=bsl.add_sea_level_change,
            kwargs=dict(
                bct_file=bct_file,
                sea_level_change_m=sl_value,
                constant=constant,
            ),
            log_textbox=self.log_textbox,
            progress_bar=self.progress_bar,
            eta_label=self.eta_label,
            on_complete=self._on_complete,
            on_error=self._on_error,
            on_cancel=self._on_cancel,
            root=self,
        )
        self._task.start()

    def _on_complete(self, result):
        out = Path(result.get('output_file', '')).name
        mode = result.get('mode', '?')
        n = result.get('n_sections', '?')
        show_success_in_log(
            self.log_textbox,
            f"Sea level change applied ({mode}) to {n} sections → {out}"
        )
        self.status_label.configure(text=f"✓ Complete — {out}")
        set_widgets_state(self._interactive_widgets + [self.run_btn], "normal")

    def _on_error(self, exc):
        self.status_label.configure(text=f"✗ Error: {exc}")
        set_widgets_state(self._interactive_widgets + [self.run_btn], "normal")
        show_error_dialog(self, "Sea Level Error", str(exc))

    def _on_cancel(self):
        self.status_label.configure(text="Cancelled")
        set_widgets_state(self._interactive_widgets + [self.run_btn], "normal")

    # ─── Settings: Save / Load / Reset ───────────────────────────────────

    def _collect_settings(self) -> dict:
        return {
            "module": MODULE_ID,
            "version": SETTINGS_VERSION,
            "values": {
                "bct_file": self.bct_entry.get().strip(),
                "sea_level_change_m": self.sl_entry.get().strip(),
                "mode": self.mode_var.get(),
            },
        }

    def _apply_settings(self, settings: dict) -> None:
        if settings.get("module") != MODULE_ID:
            raise ValueError(
                f"Settings file is for '{settings.get('module')}', "
                f"not '{MODULE_ID}'"
            )
        values = settings.get("values", {})
        self.bct_entry.delete(0, "end")
        self.bct_entry.insert(0, values.get("bct_file", ""))
        self.sl_entry.delete(0, "end")
        self.sl_entry.insert(0, str(values.get("sea_level_change_m", "")))
        mode = values.get("mode", "linear")
        if mode in ("linear", "constant"):
            self.mode_var.set(mode)

    def _on_save_settings(self):
        path = save_settings_dialog(self, default_name=f"{MODULE_ID}_settings.json")
        if not path:
            return
        try:
            save_json_settings(path, self._collect_settings())
            self.status_label.configure(text=f"Settings saved → {Path(path).name}")
        except Exception as exc:
            show_error_dialog(self, "Save Failed", f"Could not save settings:\n{exc}")

    def _on_load_settings(self):
        path = load_settings_dialog(self)
        if not path:
            return
        try:
            data = load_json_settings(path)
            self._apply_settings(data)
            self.status_label.configure(text=f"Settings loaded ← {Path(path).name}")
        except Exception as exc:
            show_error_dialog(self, "Load Failed", f"Could not load settings:\n{exc}")

    def _on_reset(self):
        if self._task is not None and self._task.is_running:
            self._task.cancel()
            self.status_label.configure(text="Stopping — will reset when finished...")
            self.after(200, self._reset_when_idle)
            return
        self._reset_ui_to_defaults()

    def _reset_when_idle(self):
        if self._task is not None and self._task.is_running:
            self.after(200, self._reset_when_idle)
            return
        self._reset_ui_to_defaults()

    def _reset_ui_to_defaults(self):
        self.bct_entry.delete(0, "end")
        self.sl_entry.delete(0, "end")
        self.mode_var.set("linear")

        clear_log(self.log_textbox)
        if self.progress_bar:
            self.progress_bar.set(0)
        self.eta_label.configure(text="")
        self.status_label.configure(text="Ready")
        set_widgets_state(self._interactive_widgets + [self.run_btn], "normal")
        self._task = None


if __name__ == '__main__':
    apply_theme()
    root = ctk.CTk()
    root.withdraw()
    win = SeaLevelWindow(root)
    win.protocol("WM_DELETE_WINDOW", root.destroy)
    root.mainloop()
